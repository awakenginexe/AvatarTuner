using System;
using System.IO;
using AvatarTuner.Editor.Optimization;

namespace AvatarTuner.StandaloneTests
{
    public static class GenerationTransactionTests
    {
        [Test("cancelled regeneration restores old bytes and GUID metadata and removes new files")]
        public static void RollbackRestoresExistingOutput()
        {
            var root = Path.Combine(Path.GetTempPath(), "AvatarTuner-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(root);
            try
            {
                var output = Path.Combine(root, "outputs");
                Directory.CreateDirectory(output);
                var old = Path.Combine(output, "old.png");
                var added = Path.Combine(output, "added.png");
                File.WriteAllText(old, "original output");
                File.WriteAllText(old + ".meta", "guid: stable");
                using (var transaction = new GeneratedFileTransaction(output, Path.Combine(root, "backups")))
                {
                    transaction.Record(old);
                    transaction.Record(added);
                    File.WriteAllText(old, "changed");
                    File.WriteAllText(old + ".meta", "guid: wrong");
                    File.WriteAllText(added, "new");
                    File.WriteAllText(added + ".meta", "new meta");
                }
                Assert.AreEqual("original output", File.ReadAllText(old), "previous generated bytes restored");
                Assert.AreEqual("guid: stable", File.ReadAllText(old + ".meta"), "GUID preserved");
                Assert.IsFalse(File.Exists(added) || File.Exists(added + ".meta"), "new output removed");
            }
            finally { Directory.Delete(root, true); }
        }

        [Test("output transactions refuse source paths outside generated root")]
        public static void SourcePathsAreRejected()
        {
            var root = Path.Combine(Path.GetTempPath(), "AvatarTuner-" + Guid.NewGuid().ToString("N"));
            try
            {
                using (var transaction = new GeneratedFileTransaction(Path.Combine(root, "generated"), Path.Combine(root, "backups")))
                    Assert.Throws<InvalidOperationException>(() => transaction.Record(Path.Combine(root, "source.png")), "outside generated root");
            }
            finally { if (Directory.Exists(root)) Directory.Delete(root, true); }
        }

        [Test("a read-only prior manifest survives a failed save and backup cleanup")]
        public static void ReadOnlyRecoveryRecordSurvives()
        {
            var root = Path.Combine(Path.GetTempPath(), "AvatarTuner-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(root);
            var manifest = Path.Combine(root, "generated", "manifest.json");
            Directory.CreateDirectory(Path.GetDirectoryName(manifest));
            File.WriteAllText(manifest, "old recovery state");
            File.SetAttributes(manifest, FileAttributes.ReadOnly);
            try
            {
                using (var transaction = new GeneratedFileTransaction(Path.GetDirectoryName(manifest), Path.Combine(root, "backup")))
                    transaction.Record(manifest);
                Assert.AreEqual("old recovery state", File.ReadAllText(manifest), "read-only state is retained");
            }
            finally { File.SetAttributes(manifest, FileAttributes.Normal); Directory.Delete(root, true); }
        }

        [Test("cancellation requested by a final progress callback prevents a successful result")]
        public static void ProgressCancellationIsHonored()
        {
            var requested = false;
            var result = new TextureGenerationResult { Succeeded = true };
            Assert.IsFalse(result.CancelIfRequested(() => requested), "work can continue before cancellation");
            requested = true;
            Assert.IsTrue(result.CancelIfRequested(() => requested), "post-progress cancellation is observed");
            Assert.IsTrue(result.Cancelled, "the run is cancelled");
            Assert.IsFalse(result.Succeeded, "cancelled work cannot commit as successful");
        }
    }
}
