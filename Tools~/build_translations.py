def build():
    by_lang = {"en": {}, "th": {}, "zh-Hans": {}}
    order = []

    for key, en, th, zh in ENTRIES:
        if key in by_lang["en"]:
            raise SystemExit("duplicate key in table: " + key)
        order.append(key)
        by_lang["en"][key] = en
        by_lang["th"][key] = th
        by_lang["zh-Hans"][key] = zh

    meta = {
        "en": ("en", "English"),
        "th": ("th", "ไทย (Thai)"),
        "zh-Hans": ("zh-Hans", "简体中文 (Simplified Chinese)"),
    }

    out_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "Editor", "Localization", "Translations")
    os.makedirs(out_dir, exist_ok=True)

    written = []
    for code in ("en", "th", "zh-Hans"):
        language_code, display = meta[code]
        entries = {k: by_lang[code][k] for k in order}
        doc = {
            "schemaVersion": 1,
            "languageCode": language_code,
            "displayName": display,
            "isFallback": code == "en",
            "entries": entries,
        }
        path = os.path.join(out_dir, code + ".json")
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            json.dump(doc, handle, ensure_ascii=False, indent=2, sort_keys=False)
            handle.write("\n")
        written.append((path, len(entries)))

    print("wrote %d translation file(s), %d keys each" % (len(written), len(order)))
    for path, count in written:
        print("  %s (%d keys)" % (path, count))
    return 0


if __name__ == "__main__":
    sys.exit(build())
